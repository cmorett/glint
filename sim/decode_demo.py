"""Command-line demo of the SPOT decoder on SYNTHETIC camera frames.

    python decode_demo.py                 # 3 chips on an organoid surface, scanning-head camera
    python decode_demo.py --mod 0.002     # weaker blink (modulation depth 0.2 %)
    python decode_demo.py --noise 0.01 --no-ref   # 1 % light-source noise, no reference region

Nothing here is measured data: frames are generated by timesim.py from a stated photon
budget and noise model, then decoded by decoder.py, which does not see the ground truth.
"""
import argparse

import numpy as np

import config_v2 as C
import decoder
import timesim


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--mod", type=float, default=0.05, help="modulation (e_on - e_off) / e_mean")
    ap.add_argument("--electrons", type=float, default=2e5, help="chip electrons per frame (whole image)")
    ap.add_argument("--bg", type=float, default=30.0, help="background electrons per um^2 per frame")
    ap.add_argument("--cycles", type=int, default=10, help="carrier cycles per bit")
    ap.add_argument("--noise", type=float, default=1e-3, help="light-source RMS noise (fraction)")
    ap.add_argument("--no-ref", action="store_true", help="disable common-mode reference correction")
    ap.add_argument("--seed", type=int, default=1)
    a = ap.parse_args()

    cam = C.CAMERAS["scan_NA0.25"]
    rng = np.random.default_rng(a.seed)
    sp = 10.0                                   # superpixel (um) = 2x2 camera pixels
    pts = rng.normal(0, 12, (4000, 2))          # blurred SPOT image, ~12 um RMS
    truth = [(17, 42), (99, 200), (250, 7)]
    sites = [(6, 6), (6, 18), (18, 12)]
    chips = [dict(pos_um=(x * sp + 5, y * sp + 5), pts_um=pts, e_mean=a.electrons, e_mod=a.mod * a.electrons,
                  id=i, value=v) for (i, v), (y, x) in zip(truth, sites)]
    sc = timesim.make_scene(chips, (24, 24), sp, cam["fps"], cam["blink_hz"], a.cycles, a.bg,
                            cam["read_noise"] * 2, rng, sigma_src=a.noise)
    T = (C.FRAME_BITS + 2) * a.cycles / cam["blink_hz"]
    print(f"SYNTHETIC DATA: {len(chips)} chips, modulation {a.mod:g}, {a.cycles} cycles/bit, "
          f"read {T:.2f} s at {cam['fps']:g} fps, source noise {a.noise:g}, reference {'off' if a.no_ref else 'on'}")
    frames = timesim.render(sc, T, rng)
    found = decoder.decode(frames, cam["fps"], cam["blink_hz"], a.cycles, use_reference=not a.no_ref, radius_px=3)
    print(f"decoder found {len(found)} chip(s):")
    for d in sorted(found, key=lambda d: (round(d['y']), d['x'])):
        print(f"  at pixel ({d['x']:.1f}, {d['y']:.1f}): ID {d['id']:3d}  value {d['value']:3d}  "
              f"preamble {'ok' if d['preamble_ok'] else 'BAD'}  carrier {d['f']:.2f} Hz")
    print("truth:", ", ".join(f"ID {i} value {v} at ({x}, {y})" for (i, v), (y, x) in zip(truth, sites)))


if __name__ == "__main__":
    main()
