"""Builds results/tables.md (the numbers quoted in SUMMARY.md) from aggregated rows."""
import os

import numpy as np

import config as C

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results")
BASE = dict(NA=C.NA_BASELINE, irradiance_mWcm2=C.IRRADIANCE_BASELINE, dR=C.DELTA_R_BASELINE,
            mua=C.MUA_BASELINE)


def pick(rows, **kw):
    return [r for r in rows if all(r[k] == v for k, v in kw.items())]


def max_depth(rows, a, lam, musp, ok, **base):
    """Deepest depth such that the chip is OK at that depth and every shallower one."""
    cfg = dict(BASE, **base)
    top = pick(rows, placement="A_top", depth_um=0, spot_um=a, wavelength_nm=lam, musp_780=musp, **cfg)
    emb = sorted(pick(rows, placement="C_embedded", spot_um=a, wavelength_nm=lam, musp_780=musp, **cfg),
                 key=lambda r: r["depth_um"])
    if not top or not ok(top[0]):
        return "none"
    best = "0"
    for r in emb:
        if ok(r):
            best = str(r["depth_um"])
        else:
            return best if best != "0" else "<50"
    return f">={best}"


def cross_depth(rows, a, lam, musp, floor, **base):
    """Depth (um) where m falls to `floor`, log-linear interpolation between grid depths."""
    cfg = dict(BASE, **base)
    pts = sorted([r for r in rows if r["spot_um"] == a and r["wavelength_nm"] == lam and r["musp_780"] == musp
                  and r["placement"] in ("A_top", "C_embedded") and all(r[k] == v for k, v in cfg.items())],
                 key=lambda r: r["depth_um"])
    if pts[0]["m"] < floor:
        return "none"
    for p, q in zip(pts, pts[1:]):
        if q["m"] < floor:
            f = (np.log(p["m"]) - np.log(floor)) / (np.log(p["m"]) - np.log(q["m"]))
            return f"~{p['depth_um'] + f * (q['depth_um'] - p['depth_um']):.0f}"
    return f">{pts[-1]['depth_um']}"


def readable(prefix):
    return lambda r: r["verdict_" + prefix] == "readable"


def above(floor):
    return lambda r: r["m"] >= floor


def blur_depth(brows, a, lam, musp):
    rs = sorted(pick(brows, placement="C_embedded", wavelength_nm=lam, musp_780=musp, mua=C.MUA_BASELINE),
                key=lambda r: r["depth_um"])
    prev_d, prev_v = 0.0, 0.0
    for r in rs:
        v = 2 * r["point_r50_surface_um"]
        if v > a:
            d = prev_d + (a - prev_v) * (r["depth_um"] - prev_d) / (v - prev_v)
            return f"{d:.0f}"
        prev_d, prev_v = r["depth_um"], v
    return f">{rs[-1]['depth_um']}"


def fmt(x, p=3):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "inf"
    return f"{x:.{p}g}"


def main(res, sres, bres, cres):
    L = []
    L.append("# Generated tables (do not edit; regenerated by run_all.py)\n")
    L.append(f"Baseline unless stated: NA {C.NA_BASELINE}, irradiance {C.IRRADIANCE_BASELINE} mW/cm2, "
             f"dR {C.DELTA_R_BASELINE} around R={C.R_MEAN}, mu_a {C.MUA_BASELINE}/mm, 150 Hz blink. "
             "mu_s' values are at 780 nm (scaled to other wavelengths with b=1.286).\n")

    L.append("## 1. Maximum depth (um), placement C: shot-noise readable (camera model) / m >= 1e-3 / m >= 1e-4\n")
    L.append("(1000 um is the deepest simulated depth, so '>=1000' / '>1000' means OK at every simulated depth. "
             "The m columns interpolate log(m) linearly between simulated depths.)\n")
    L.append("| SPOT | mu_s'(780) | " + " | ".join(f"{l} nm" for l in C.WAVELENGTHS_NM) + " |")
    L.append("|---|---|" + "---|" * len(C.WAVELENGTHS_NM))
    for a in C.SPOT_SIZES_UM:
        for mu in C.MUSP_780_PER_MM:
            cells = []
            for lam in C.WAVELENGTHS_NM:
                cells.append(" / ".join([max_depth(res, a, lam, mu, readable("cam")),
                                         cross_depth(res, a, lam, mu, 1e-3),
                                         cross_depth(res, a, lam, mu, 1e-4)]))
            L.append(f"| {a} um | {mu} | " + " | ".join(cells) + " |")

    L.append("\n## 2. Wavelength-shift scenario (HYPOTHETICAL), 780 nm: max depth (um) with m >= 1e-3 [m at 1000 um]\n")
    combos = [(1e2, 0.01), (1e3, 0.1), (1e4, 0.1), (1e4, 1.0)]
    L.append("| SPOT | mu_s'(780) | no shift | " + " | ".join(f"filter {f:.0e}, eff {e:.0%}" for f, e in combos) + " |")
    L.append("|---|---|---|" + "---|" * len(combos))
    for a in C.SPOT_SIZES_UM:
        for mu in C.MUSP_780_PER_MM:
            def m1000(rows):
                r = pick(rows, placement="C_embedded", depth_um=1000, spot_um=a, wavelength_nm=780,
                         musp_780=mu, NA=C.NA_BASELINE, irradiance_mWcm2=C.IRRADIANCE_BASELINE,
                         mua=C.MUA_BASELINE, dR=C.DELTA_R_BASELINE)[0]
                return f"{r['m']:.2g}"
            cells = [cross_depth(res, a, 780, mu, 1e-3) + f" [{m1000(res)}]"]
            for f, e in combos:
                sub = pick(sres, filter=f, efficiency=e)
                cells.append(cross_depth(sub, a, 780, mu, 1e-3) + f" [{m1000(sub)}]")
            L.append(f"| {a} um | {mu} | " + " | ".join(cells) + " |")

    L.append("\n## 3. Lateral blur: depth (um) at which the point-mirror spread (2 x r50 at the exit surface) exceeds the SPOT side\n")
    L.append("| mu_s'(780) | wavelength | a=30 | a=100 | a=300 | point r50 at 100 um depth | at 300 um |")
    L.append("|---|---|---|---|---|---|---|")
    for mu in C.MUSP_780_PER_MM:
        for lam in C.WAVELENGTHS_NM:
            r100 = pick(bres, placement="C_embedded", depth_um=100, wavelength_nm=lam, musp_780=mu, mua=C.MUA_BASELINE)[0]
            r300 = pick(bres, placement="C_embedded", depth_um=300, wavelength_nm=lam, musp_780=mu, mua=C.MUA_BASELINE)[0]
            L.append(f"| {mu} | {lam} | " + " | ".join(blur_depth(bres, a, lam, mu) for a in C.SPOT_SIZES_UM)
                     + f" | {r100['point_r50_surface_um']:.0f} um | {r300['point_r50_surface_um']:.0f} um |")

    L.append("\n## 4. Embedded chip, 780 nm, mu_s' 1.0: key numbers vs depth (a = 100 um)\n")
    L.append("| depth | F_down | ballistic part | C_NA | image r50 | bg/area | m | SNR/cycle cam | t cam (s) | verdict |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    rs = sorted(pick(res, spot_um=100, wavelength_nm=780, musp_780=1.0, **BASE), key=lambda r: (r["placement"], r["depth_um"]))
    for r in rs:
        L.append(f"| {r['placement']} {r['depth_um']} | {fmt(r['F_down'])} | {fmt(r['F_ballistic'])} | "
                 f"{fmt(r['C_NA'])} +/- {fmt(r['C_NA_err'], 2)} | {fmt(r['img_r50_um'])} | {fmt(r['bg_per_area'])} | "
                 f"{fmt(r['m'])} +/- {fmt(r['m_err'], 2)} | {fmt(r['snr_cam'])} | {fmt(r['t_cam_s'])} | {r['verdict_cam']} |")

    L.append("\n## 5. Surface placements (d = 0), 780 nm, mu_s' 1.0\n")
    L.append("| placement | SPOT | bg/area | m | t cam (s) |")
    L.append("|---|---|---|---|---|")
    for p in ("A_top", "B_under"):
        for a in C.SPOT_SIZES_UM:
            r = pick(res, placement=p, depth_um=0, spot_um=a, wavelength_nm=780, musp_780=1.0, **BASE)[0]
            L.append(f"| {p} | {a} | {fmt(r['bg_per_area'])} | {fmt(r['m'])} | {fmt(r['t_cam_s'])} |")
    worst = [r for r in res if r["depth_um"] == 0]
    nr = [r for r in worst if r["verdict_cam"] != "readable"]
    L.append(f"\nAcross ALL swept settings, d = 0 configurations readable (camera): "
             f"{len(worst) - len(nr)}/{len(worst)}; min m = {fmt(min(r['m'] for r in worst))}.\n")

    L.append("\n## 6. Sensitivity (a = 100 um, 780 nm, mu_s' 1.0): max depth readable (camera) / with m >= 1e-3\n")
    L.append("| NA \\ irradiance | " + " | ".join(f"{E} mW/cm2" for E in C.IRRADIANCE_MW_CM2) + " |")
    L.append("|---|" + "---|" * len(C.IRRADIANCE_MW_CM2))
    for na in C.NA_LIST:
        L.append(f"| {na} | " + " | ".join(max_depth(res, 100, 780, 1.0, readable("cam"), NA=na, irradiance_mWcm2=E)
                                           + " / " + max_depth(res, 100, 780, 1.0, above(1e-3), NA=na, irradiance_mWcm2=E)
                                           for E in C.IRRADIANCE_MW_CM2) + " |")
    L.append("\n| dR | mu_a 0.01 | mu_a 0.02 | mu_a 0.05 |")
    L.append("|---|---|---|---|")
    for dR in C.DELTA_R:
        L.append(f"| {dR} | " + " | ".join(max_depth(res, 100, 780, 1.0, readable("cam"), dR=dR, mua=mua)
                                            + " / " + max_depth(res, 100, 780, 1.0, above(1e-3), dR=dR, mua=mua)
                                            for mua in C.MUA_PER_MM) + " |")

    L.append("\n## 7. Power check: irradiance needed for 1 uW optical on a 100x100 um cell "
             "(= 100 nW electrical at 10%, our estimate), mu_a 0.02\n")
    L.append("| mu_s'(780) | wavelength | " + " | ".join(f"d={d}" for d in [0] + C.DEPTHS_C_UM) + " |")
    L.append("|---|---|" + "---|" * (1 + len(C.DEPTHS_C_UM)))
    for mu in C.MUSP_780_PER_MM:
        for lam in C.WAVELENGTHS_NM:
            cells = []
            for d in [0] + C.DEPTHS_C_UM:
                p = "A_top" if d == 0 else "C_embedded"
                r = pick(res, placement=p, depth_um=d, spot_um=100, wavelength_nm=lam, musp_780=mu, **BASE)[0]
                cells.append(f"{r['E_needed_mWcm2']:.1f}")
            L.append(f"| {mu} | {lam} | " + " | ".join(cells) + " |")
    L.append("(mW/cm2; F_down can exceed 1 near the surface because backscattered light adds to the downward flux.)")

    L.append("\n## 8. Chicken-skin sanity check (250 um skin, mu_s' 2.45/mm, 780 nm)\n")
    L.append("| NA | SPOT | irradiance | point r50 | image r50 | m | t cam (s) | t ideal (s) |")
    L.append("|---|---|---|---|---|---|---|---|")
    for r in sorted(cres, key=lambda r: (r["NA"], r["spot_um"], r["irradiance_mWcm2"])):
        if r["irradiance_mWcm2"] != C.IRRADIANCE_BASELINE:
            continue
        L.append(f"| {r['NA']} | {r['spot_um']} | {r['irradiance_mWcm2']} | {r['point_r50_surface_um']:.0f} | "
                 f"{r['img_r50_um']:.0f} | {fmt(r['m'])} | {fmt(r['t_cam_s'])} | {fmt(r['t_ideal_s'])} |")

    with open(os.path.join(OUT, "tables.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L))


def _load(path):
    import csv
    rows = []
    with open(path) as f:
        for r in csv.DictReader(f):
            for k, v in r.items():
                if v in ("True", "False"):
                    r[k] = v == "True"
                else:
                    try:
                        r[k] = float(v)
                        if r[k].is_integer() and k in ("depth_um", "spot_um", "wavelength_nm"):
                            r[k] = int(r[k])
                    except ValueError:
                        pass
            rows.append(r)
    return rows


if __name__ == "__main__":   # rebuild tables.md from the CSVs without re-running the sweep
    main(_load(os.path.join(OUT, "results.csv")), _load(os.path.join(OUT, "results_wavelength_shift.csv")),
         _load(os.path.join(OUT, "blur_point_mirror.csv")), _load(os.path.join(OUT, "sanity_chicken_skin.csv")))
