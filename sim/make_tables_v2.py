"""Round-2 tables (results/v2/tables_v2.md) plus deck_chart.csv, plate_time.csv, dose.csv."""
import csv
import math
import os
import pickle
import sys

import numpy as np

import config_v2 as C

SYMBOLS = C.FRAME_BITS + 2          # symbols in one read (29 bits + reference + timing margin)
MIN_NC = 2
HEAD = dict(wavelength_nm=C.HEADLINE_WAVELENGTH, musp_780=C.MUSP_BASELINE, refl=C.HEADLINE_REFLECTANCE,
            irradiance=C.IRRADIANCE_BASELINE)


def pick(rows, **kw):
    return [r for r in rows if all(r.get(k) == v for k, v in kw.items())]


def one(rows, **kw):
    p = pick(rows, **kw)
    if not p:
        raise KeyError(kw)
    return p[0]


def fmt(x, p=2):
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "never"
    return f"{x:.{p}g}"


class Rule:
    """Decode rule calibrated on the decoder runs on synthetic frames.

    A read decodes if SNR/cycle * sqrt(cycles per bit) >= req(depth). req comes from ALL decoder
    evidence: the floor searches (reference on) and every BER run. For each depth regime the
    threshold is 1.2x the largest SNR at which any run still failed (>1 of 12 frames wrong).
    Deep (> 500 um) chips need a much higher threshold: their images are faint and spread out,
    and this decoder's chip-finding and pixel weighting lose efficiency there.
    """
    SPLIT_UM = 500

    def __init__(self, frows, bers=()):
        sc = [f["snr_symbol_ideal_at_min"] for f in frows if f["reference"] and math.isfinite(f["snr_symbol_ideal_at_min"])]
        self.floor_worst = float(np.max(sc)) if sc else float("nan")
        self.floor_median = float(np.median(sc)) if sc else float("nan")
        fail_sh = [b["snr1"] * math.sqrt(b["n_c"]) for b in bers
                   if b["frames_ok"] < b["frames"] - 1 and b["depth_um"] <= self.SPLIT_UM]
        fail_dp = [b["snr1"] * math.sqrt(b["n_c"]) for b in bers
                   if b["frames_ok"] < b["frames"] - 1 and b["depth_um"] > self.SPLIT_UM]
        self.req_shallow = 1.2 * max([self.floor_worst] + fail_sh)
        self.req_deep = 1.2 * max([self.req_shallow / 1.2] + fail_dp)
        self.req = self.req_shallow

    def req_for(self, row):
        return self.req_deep if row.get("depth_um", 0) > self.SPLIT_UM else self.req_shallow

    def n_c(self, snr1, req=None):
        req = self.req if req is None else req
        if not snr1 or snr1 <= 0 or not math.isfinite(snr1):
            return math.inf
        return max(MIN_NC, math.ceil((req / snr1) ** 2))

    def t_read(self, row):
        nc = self.n_c(row["snr1"], self.req_for(row))
        return SYMBOLS * nc / row["blink_hz"] if math.isfinite(nc) else math.inf

    def ok(self, row):
        return self.t_read(row) <= C.READ_LIMIT_S


def write_csv(path, rows):
    cols = list(rows[0].keys())
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for r in rows:
            w.writerow({k: (f"{v:.6g}" if isinstance(v, float) else v) for k, v in r.items()})


def tilt_limit_deg(NA, n=C.N_MEDIUM):
    return math.degrees(0.5 * math.asin(min(1.0, 2 * NA / n)))


def readable_fraction(rows_by_tilt, rule, req):
    """Fraction of uniformly random orientations that decode within 60 s (log-SNR interpolation)."""
    pts = sorted((r["tilt"], r["snr1"]) for r in rows_by_tilt)
    tg = np.array([p[0] for p in pts]); sg = np.array([max(p[1], 1e-30) for p in pts])
    fine = np.arange(0, 180.0001, 0.02)
    ls = np.interp(fine, tg, np.log(sg), right=np.log(1e-30))
    snr = np.exp(ls)
    nc = np.maximum(MIN_NC, np.ceil((req / snr) ** 2))
    t = SYMBOLS * nc / rows_by_tilt[0]["blink_hz"]
    ok = t <= C.READ_LIMIT_S
    w = np.sin(np.radians(fine)) * np.radians(0.02) / 2
    frac = float((w * ok).sum())
    tmax = float(fine[np.argmin(ok)]) if not ok.all() else 180.0
    return frac, tmax


def main(res, tres, sres, frows, bers, out):
    rule = Rule(frows, bers)
    L = ["# Round-2 tables (generated by run_v2.py; do not edit)\n",
         f"Headline settings unless stated: 780 nm, mu_s' 1.0/mm (at 780), mu_a 0.02/mm, 10 mW/cm2, "
         f"reflectance R_on/R_off = {C.R_ON_PAPER:.3f}/{C.R_OFF_PAPER:.3f} (paper, measured at 635 nm; applied at 780 nm "
         f"as an optimistic assumption). 'Read' = decode a 29-bit frame (ID + value), using the decoder-calibrated rule "
         f"SNR/cycle x sqrt(cycles per bit) >= {rule.req_shallow:.0f} for chips <= 500 um deep and "
         f">= {rule.req_deep:.0f} deeper (1.2x the highest SNR at which any decoder run still failed; the floor "
         f"searches alone gave a median of {rule.floor_median:.1f}, worst {rule.floor_worst:.1f}).\n"]

    # ---------------- Task 1
    L.append("## 1. Whole-plate optics: time to read one chip (s), flat chip, 100 um SPOT unless stated [modulation m]\n")
    cams = ["plate20MP_NA0.01", "plate20MP_NA0.02", "plate20MP_NA0.05", "plate60MP_NA0.02", "plate60MP_NA0.05",
            "4x20MP_NA0.04", "16x20MP_NA0.08", "scan_NA0.25"]
    cols = [("A_top", 0, 30), ("A_top", 0, 100), ("B_under", 0, 100), ("C_embedded", 100, 100),
            ("C_embedded", 300, 100), ("C_embedded", 300, 300), ("C_embedded", 1000, 300)]
    L.append("| camera | NA | object pixel | blink Hz | specular tilt limit | " +
             " | ".join(f"{p.split('_')[0]} d={d} a={a}" for p, d, a in cols) + " |")
    L.append("|---|---|---|---|---|" + "---|" * len(cols))
    for cn in cams:
        cam = C.CAMERAS[cn]
        cells = []
        for p, d, a in cols:
            r = one(res, placement=p, depth_um=d, spot_um=a, cam=cn, **HEAD)
            cells.append(f"{fmt(rule.t_read(r))} [{fmt(r['m'])}]")
        L.append(f"| {cn} | {cam['NA']:.2g} | {cam['obj_pixel_um']:.1f} um | {cam['blink_hz']:g} | "
                 f"{tilt_limit_deg(cam['NA']):.2f} deg | " + " | ".join(cells) + " |")

    # plate time
    pt = []
    for arch, cn, kind in [("1 fixed 20 MP camera", "plate20MP_NA0.02", "fixed"),
                           ("1 fixed 60 MP camera", "plate60MP_NA0.02", "fixed"),
                           ("4 fixed 20 MP cameras", "4x20MP_NA0.04", "fixed"),
                           ("16 fixed 20 MP cameras", "16x20MP_NA0.08", "fixed"),
                           ("scanning head NA 0.25", "scan_NA0.25", "scan")]:
        for chip, (p, d, a) in [("surface (A), a=100", ("A_top", 0, 100)), ("under (B), a=100", ("B_under", 0, 100)),
                                ("embedded 300 um, a=100", ("C_embedded", 300, 100)),
                                ("embedded 300 um, a=300", ("C_embedded", 300, 300))]:
            r = one(res, placement=p, depth_um=d, spot_um=a, cam=cn, **HEAD)
            t = rule.t_read(r)
            for wells, nw in C.WELLS.items():
                plate = t if kind == "fixed" else nw * (C.SCAN_HEAD["move_settle_s"] + t)
                pt.append(dict(architecture=arch, camera=cn, chip=chip, wells=wells, read_per_chip_s=t,
                               plate_time_s=plate, specular_tilt_limit_deg=tilt_limit_deg(C.CAMERAS[cn]["NA"])))
    write_csv(os.path.join(out, "plate_time.csv"), pt)
    L.append("\n## 1b. Time to read a whole plate (flat chips; scanning head adds "
             f"{C.SCAN_HEAD['move_settle_s']} s move+settle per well)\n")
    L.append("| architecture | tilt limit | chip | 96-well | 384-well |")
    L.append("|---|---|---|---|---|")
    for i in range(0, len(pt), 2):
        a, b = pt[i], pt[i + 1]
        L.append(f"| {a['architecture']} | {a['specular_tilt_limit_deg']:.2f} deg | {a['chip']} | "
                 f"{fmt(a['plate_time_s'])} s | {fmt(b['plate_time_s'])} s |")

    # ---------------- Task 2
    L.append("\n## 2. Spheres: can a chip at the CENTRE be read within 60 s? time (s) [m]; above = camera on top, below = through the dish\n")
    L.append("| D (mm) | SPOT | mu_s' | above, scan NA 0.25 | below, scan NA 0.25 | above, plate NA 0.02 | below, plate NA 0.02 |")
    L.append("|---|---|---|---|---|---|---|")
    for D in C.SPHERE_DIAMETERS_MM:
        for a in C.SPOT_SIZES_UM:
            for mu in C.MUSP_780_PER_MM:
                cells = []
                for cn in ("scan_NA0.25", "plate20MP_NA0.02"):
                    for side in ("above", "below"):
                        r = one(sres, placement="center", side=side, D_mm=D, spot_um=a, musp_780=mu, cam=cn)
                        t = rule.t_read(r)
                        cells.append(("yes " if t <= 60 else "NO ") + f"{fmt(t)} [{fmt(r['m'])}]")
                L.append(f"| {D} | {a} | {mu} | " + " | ".join([cells[0], cells[1], cells[2], cells[3]]) + " |")
    L.append("\n### 2b. Other positions (scan NA 0.25, 100 um SPOT, mu_s' 1.0): time (s) [m]\n")
    L.append("| D (mm) | position | depth from camera side | above | below |")
    L.append("|---|---|---|---|---|")
    for D in C.SPHERE_DIAMETERS_MM:
        for pos in ("surface", "halfway", "center", "far_surface"):
            cells = []
            for side in ("above", "below"):
                r = one(sres, placement=pos, side=side, D_mm=D, spot_um=100, musp_780=1.0, cam="scan_NA0.25")
                cells.append(f"{fmt(rule.t_read(r))} [{fmt(r['m'])}]")
            L.append(f"| {D} | {pos} | {pick(sres, placement=pos, D_mm=D)[0]['depth_um']} um | {cells[0]} | {cells[1]} |")
    L.append("\n### 2c. Slab vs sphere at the same depth (centre chip, read from above, 100 um SPOT, scan NA 0.25)\n")
    L.append("| D (mm) | mu_s' | depth | signal (sphere/slab) | background (sphere/slab) | m (sphere/slab) |")
    L.append("|---|---|---|---|---|---|")
    for D in C.SPHERE_DIAMETERS_MM:
        for mu in C.MUSP_780_PER_MM:
            s = one(sres, placement="center", side="above", D_mm=D, spot_um=100, musp_780=mu, cam="scan_NA0.25")
            d = int(round(D * 500))
            try:
                b = one(res, placement="C_embedded", depth_um=d, spot_um=100, cam="scan_NA0.25",
                        wavelength_nm=780, musp_780=mu, refl=C.HEADLINE_REFLECTANCE, irradiance=10.0)
            except KeyError:
                continue
            L.append(f"| {D} | {mu} | {d} um | {s['sig_frac_um2'] / b['sig_frac_um2']:.2f} | "
                     f"{s['bg_dens'] / b['bg_dens']:.2f} | {s['m'] / b['m']:.2f} |")

    # ---------------- Task 3
    L.append("\n## 3. Tilt: signal relative to a flat chip (100 um SPOT, mirror unless stated)\n")
    tilts = C.TILTS_DEG
    L.append("| chip | NA | " + " | ".join(f"{t} deg" for t in tilts) + " |")
    L.append("|---|---|" + "---|" * len(tilts))
    for d in [0] + C.TILT_DEPTHS_UM:
        for cn in ("plate20MP_NA0.02", "plate20MP_NA0.05", "scan_NA0.25"):
            pl = "B_under" if d == 0 else "C_embedded"
            rs = pick(tres, placement=pl, depth_um=d, cam=cn, mode="specular", spot_um=100)
            s0 = [r for r in rs if r["tilt"] == 0][0]
            base = s0["irr"] * s0["C_NA"]
            cells = []
            for t in tilts:
                rr = [r for r in rs if r["tilt"] == t]
                cells.append(fmt(rr[0]["irr"] * rr[0]["C_NA"] / base) if rr and base > 0 else "-")
            L.append(f"| {'no tissue' if d == 0 else f'{d} um deep'} | {C.CAMERAS[cn]['NA']} | " + " | ".join(cells) + " |")
    L.append("\n### 3b. Fraction of random orientations readable within 60 s, and the settle-flat / Lambertian options\n")
    L.append("| chip | camera | mirror: random orientation | mirror: max tilt | mirror settled flat (50% face-down, tilt <= 2 deg) | Lambertian: random orientation | Lambertian flat: time (s) [m] | mirror flat: time (s) [m] |")
    L.append("|---|---|---|---|---|---|---|---|")
    for d in [0] + C.TILT_DEPTHS_UM:
        pl = "B_under" if d == 0 else "C_embedded"
        for cn in ("plate20MP_NA0.02", "plate20MP_NA0.05", "scan_NA0.25"):
            rs = pick(tres, placement=pl, depth_um=d, cam=cn, spot_um=100)
            spec = [r for r in rs if r["mode"] == "specular"]
            lam = [r for r in rs if r["mode"] == "lambert"]
            fs, tmax = readable_fraction(spec, rule, rule.req_for(spec[0]))
            fl, _ = readable_fraction(lam, rule, rule.req_for(lam[0]))
            settle = f"{0.5 * min(1.0, tmax / C.SETTLE_TILT_DEG):.0%}" if d == 0 else "n/a"
            l0 = [r for r in lam if r["tilt"] == 0][0]; s0 = [r for r in spec if r["tilt"] == 0][0]
            L.append(f"| {'no tissue (B, SPOT facing glass)' if d == 0 else f'{d} um deep'} | {cn} | {fs:.1%} | "
                     f"{tmax:.2f} deg | {settle} | {fl:.1%} | {fmt(rule.t_read(l0))} [{fmt(l0['m'])}] | "
                     f"{fmt(rule.t_read(s0))} [{fmt(s0['m'])}] |")

    # ---------------- Task 4
    L.append("\n## 4. Decoder (synthetic frames): lowest modulation that decodes >= 23 of 24 chips\n")
    L.append("| photon budget from | read time (s) | source noise RMS | reference region | m_min | SNR/symbol at m_min (ideal) |")
    L.append("|---|---|---|---|---|---|")
    for f in frows:
        L.append(f"| {f['config']} | {f['read_s']:.3g} | {f['source_noise_rms']:g} | {'yes' if f['reference'] else 'no'} | "
                 f"{fmt(f['m_min'])} | {fmt(f['snr_symbol_ideal_at_min'])} |")
    L.append("\n### 4b. Bit error rate vs read time, decoder on synthetic frames (source noise 0.1 %, reference on)\n")
    L.append("| camera | placement | depth | SPOT | m | read time (s) | frames decoded | BER | predicted by rule |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    for b in bers:
        cam = C.CAMERAS[b["cam"]]
        pred = b["snr1"] * math.sqrt(b["n_c"]) >= rule.req_for(b)
        L.append(f"| {b['cam']} | {b['placement']} | {b['depth_um']} | {b['spot_um']} | {fmt(b['m'])} | {b['read_s']:.3g} | "
                 f"{b['frames_ok']}/{b['frames']} | {b['ber']:.3f} | {'decode' if pred else 'fail'} |")
    L.append("\n### 4c. Maximum depth (um) at which a chip decodes within 60 s (slab, flat chip)\n")
    L.append("| SPOT | mu_s' | 780 nm scan NA 0.25 | 635 nm scan NA 0.25 | 780 nm plate NA 0.02 | 780 nm: round-1 floor m >= 1e-3 (scan) |")
    L.append("|---|---|---|---|---|---|")

    def maxdepth(ok, **kw):
        deps = [0] + C.DEPTHS_V2_UM
        best = None
        for d in deps:
            pl = "A_top" if d == 0 else "C_embedded"
            r = one(res, placement=pl, depth_um=d, refl=C.HEADLINE_REFLECTANCE, irradiance=10.0, **kw)
            if ok(r):
                best = d
            else:
                break
        if best is None:
            return "none"
        return f">={best}" if best == deps[-1] else str(best)
    for a in C.SPOT_SIZES_UM:
        for mu in C.MUSP_780_PER_MM:
            L.append(f"| {a} | {mu} | " + " | ".join([
                maxdepth(rule.ok, spot_um=a, musp_780=mu, wavelength_nm=780, cam="scan_NA0.25"),
                maxdepth(rule.ok, spot_um=a, musp_780=mu, wavelength_nm=635, cam="scan_NA0.25"),
                maxdepth(rule.ok, spot_um=a, musp_780=mu, wavelength_nm=780, cam="plate20MP_NA0.02"),
                maxdepth(lambda r: r["m"] >= 1e-3, spot_um=a, musp_780=mu, wavelength_nm=780, cam="scan_NA0.25")]) + " |")

    # ---------------- Task 5
    dose = []
    for arch, cn, chip, (p, d, a), local in [
            ("scanning head, light only on the well being read", "scan_NA0.25", "surface a=100", ("A_top", 0, 100), True),
            ("scanning head, light only on the well being read", "scan_NA0.25", "embedded 300 um a=100", ("C_embedded", 300, 100), True),
            ("scanning head, whole plate lit during a 96-well scan", "scan_NA0.25", "embedded 300 um a=100", ("C_embedded", 300, 100), False),
            ("fixed whole-plate camera (flat chips)", "plate20MP_NA0.02", "surface a=100", ("A_top", 0, 100), True)]:
        r = one(res, placement=p, depth_um=d, spot_um=a, cam=cn, **HEAD)
        t = rule.t_read(r) + C.CHIP_STARTUP_S
        if not local:
            t = 96 * (C.SCAN_HEAD["move_settle_s"] + rule.t_read(r))
        for iv in C.READ_INTERVALS_MIN:
            duty = min(1.0, t / (60 * iv))
            dose.append(dict(architecture=arch, chip=chip, read_s=t, interval_min=iv, duty=duty,
                             avg_irradiance_mW_cm2=C.IRRADIANCE_BASELINE * duty,
                             daily_dose_J_cm2=C.IRRADIANCE_BASELINE * 1e-3 * duty * 86400))
    write_csv(os.path.join(out, "dose.csv"), dose)
    L.append(f"\n## 5. Light dose at {C.IRRADIANCE_BASELINE} mW/cm2 during reads (continuous light would be "
             f"{C.IRRADIANCE_BASELINE * 1e-3 * 86400:.0f} J/cm2 per day)\n")
    L.append("| architecture | chip | light-on per read (s) | every | duty | average mW/cm2 | J/cm2 per day |")
    L.append("|---|---|---|---|---|---|---|")
    for x in dose:
        L.append(f"| {x['architecture']} | {x['chip']} | {fmt(x['read_s'])} | {x['interval_min']} min | {x['duty']:.2%} | "
                 f"{x['avg_irradiance_mW_cm2']:.3g} | {x['daily_dose_J_cm2']:.3g} |")

    # ---------------- deck chart
    deck = []
    for d in [0] + C.DEPTHS_V2_UM:
        row = dict(depth_um=d)
        for a in C.SPOT_SIZES_UM:
            r = one(res, placement="A_top" if d == 0 else "C_embedded", depth_um=d, spot_um=a, cam="scan_NA0.25", **HEAD)
            row[f"m_spot{a}um"] = r["m"]; row[f"m_spot{a}um_err"] = r.get("m_err", float("nan"))
        deck.append(row)
    write_csv(os.path.join(out, "deck_chart.csv"), deck)

    open(os.path.join(out, "tables_v2.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))
    return rule


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "results", "v2")
    mc = pickle.load(open(os.path.join(out, "mc_v2.pkl"), "rb"))

    def load(p):
        rows = list(csv.DictReader(open(p)))
        for r in rows:
            for k, v in r.items():
                if v in ("True", "False"):
                    r[k] = v == "True"
                else:
                    try:
                        r[k] = float(v)
                        if k in ("depth_um", "spot_um", "n_c", "frames_ok", "frames", "false_chips"):
                            r[k] = int(r[k])
                    except ValueError:
                        pass
        return rows
    main(mc["res"], mc["tres"], mc["sres"], load(os.path.join(out, "decoder_floor.csv")),
         load(os.path.join(out, "decoder_ber.csv")), out)
