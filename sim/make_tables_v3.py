# ------------------------------------------------------------------ helpers (tested in tests/test_v3.py)
def load_csv(p):
    rows = list(csv.DictReader(open(p)))
    for r in rows:
        for k, v in r.items():
            if v in ("True", "False"):
                r[k] = v == "True"
            else:
                try:
                    r[k] = float(v)
                    if k in ("depth_um", "spot_um", "n_c", "frames_ok", "frames", "false_chips"):
                        r[k] = int(r[k])
                except ValueError:
                    pass
    return rows


def load_rule():
    return M2.Rule(load_csv(os.path.join(V2, "decoder_floor.csv")), load_csv(os.path.join(V2, "decoder_ber.csv")))


def snr_with_blink_noise(row, m_noise):
    """Per-cycle SNR when extra noise at the blink frequency produces an apparent modulation
    of RMS m_noise / sqrt(T [s]) after averaging for T seconds (m_noise in 1/sqrt(Hz))."""
    s = row["snr1"]
    if m_noise <= 0 or s <= 0:
        return s
    half = C.SAMPLES_PER_CYCLE / 2
    diff = half * (row["e_on_frame"] - row["e_off_frame"])
    var_shot = (diff / s) ** 2
    mean_half = half * (0.5 * (row["e_on_frame"] + row["e_off_frame"]) + row["e_bg_frame"])
    sx = m_noise * mean_half * math.sqrt(row["blink_hz"])
    return diff / math.sqrt(var_shot + sx * sx)


def t_read(rule, row, snr=None):
    r = dict(row)
    if snr is not None:
        r["snr1"] = snr
    return rule.t_read(r)


def orientation_stats(rule, tilt_rows, n=C.N_ORIENTATIONS, seed=5):
    """Read-time distribution for uniformly random orientations (cos(tilt) uniform in [-1, 1]),
    interpolating log(SNR/cycle) between simulated tilts."""
    pts = sorted((r["tilt"], max(r["snr1"], 1e-30)) for r in tilt_rows)
    tg = np.array([p[0] for p in pts]); ls = np.log([p[1] for p in pts])
    rng = np.random.default_rng(seed)
    tilt = np.degrees(np.arccos(rng.uniform(-1, 1, n)))
    snr = np.exp(np.interp(tilt, tg, ls))
    ref = dict(tilt_rows[0])
    t = np.array([t_read(rule, ref, s) for s in snr])
    ts = np.sort(t)
    return dict(median=float(ts[n // 2]), p90=float(ts[int(0.9 * (n - 1))]),
                f1=float(np.mean(t <= 1)), f10=float(np.mean(t <= 10)), f60=float(np.mean(t <= 60)))


def h_max_um(side_um, tilt_deg):
    return side_um * math.tan(math.radians(tilt_deg))


def fmt(x, p=2):
    if x is None or (isinstance(x, float) and not math.isfinite(x)):
        return "never"
    return f"{x:.{p}g}"


def pick(rows, **kw):
    return [r for r in rows if all(r.get(k) == v for k, v in kw.items())]


def one(rows, **kw):
    p = pick(rows, **kw)
    if not p:
        raise KeyError(kw)
    return p[0]


def max_depth(rule, res, ok=None, **kw):
    ok = ok or rule.ok
    deps = [0] + C.DEPTHS_V2_UM
    best = None
    for d in deps:
        r = one(res, placement="A_top" if d == 0 else "C_embedded", depth_um=d, **kw)
        if ok(r):
            best = d
        else:
            break
    if best is None:
        return "none"
    return f">={best}" if best == deps[-1] else str(best)


def main(res, sres, out):
    rule = load_rule()
    L = ["# Round-3 tables (generated by run_v3.py; do not edit)\n",
         f"Reflectance: R_on/R_off = {C.R_ON_PAPER:.3f}/{C.R_OFF_PAPER:.3f}, MEASURED at 635 nm (paper Fig. S11). "
         "At 780 and 850 nm the same value is EXTRAPOLATED (optimistic); x0.5 / x0.25 rows assume the true swing "
         "there is half / a quarter of it (same mean R). Tissue mu_s' values are quoted at 780 nm and scaled to "
         f"other wavelengths with b = {C.SCATTER_POWER_B}. Read = decode ID + value, round-2 calibrated rule "
         f"(SNR/cycle x sqrt(cycles/bit) >= {rule.req_shallow:.0f}, or {rule.req_deep:.0f} beyond 500 um). "
         "10 mW/cm2, mu_a 0.02/mm unless stated.\n"]

    # ---------------- Task 1a
    L.append("## 1a. Time to read one chip (s), flat chip: 635 nm measured | 780 nm extrapolated, optimistic  [m at 635]\n")
    cams = ["plate20MP_NA0.02", "plate20MP_NA0.05", "plate60MP_NA0.02", "4x20MP_NA0.04", "16x20MP_NA0.08", SCAN]
    cols = [("B_under", 0, 100, "chip on dish, SPOT down"), ("A_top", 0, 100, "on top"),
            ("C_embedded", 100, 100, "100 um deep"), ("C_embedded", 300, 100, "300 um deep"),
            ("C_embedded", 300, 300, "300 um deep, 300 um SPOT")]
    L.append("| camera | " + " | ".join(c[3] for c in cols) + " |")
    L.append("|---|" + "---|" * len(cols))
    for cn in cams:
        cells = []
        for p, d, a, _ in cols:
            r6 = one(res, placement=p, depth_um=d, spot_um=a, cam=cn, wavelength_nm=635, musp_780=1.0, **BASE)
            r7 = one(res, placement=p, depth_um=d, spot_um=a, cam=cn, wavelength_nm=780, musp_780=1.0, **BASE)
            cells.append(f"{fmt(rule.t_read(r6))} \\| {fmt(rule.t_read(r7))} [{fmt(r6['m'])}]")
        L.append(f"| {cn} | " + " | ".join(cells) + " |")
    L.append("\nWhole plate (chip on dish, SPOT down, 100 um SPOT, flat): fixed 20 MP camera = one chip read time "
             "(all wells in parallel); scanning head = wells x (0.5 s move + read).\n")
    L.append("| architecture | 635 nm 96-well | 635 nm 384-well | 780 nm 96-well |")
    L.append("|---|---|---|---|")
    for arch, cn, fixed in (("1 fixed 20 MP camera, NA 0.02", PLATE, True), ("16 fixed cameras, NA 0.08", "16x20MP_NA0.08", True),
                            ("scanning head, NA 0.25", SCAN, False)):
        tt = {}
        for lam in (635, 780):
            r = one(res, placement="B_under", depth_um=0, spot_um=100, cam=cn, wavelength_nm=lam, musp_780=1.0, **BASE)
            tt[lam] = rule.t_read(r)
        f = (lambda t, n: t) if fixed else (lambda t, n: n * (C.SCAN_HEAD["move_settle_s"] + t))
        L.append(f"| {arch} | {fmt(f(tt[635], 96))} s | {fmt(f(tt[635], 384))} s | {fmt(f(tt[780], 96))} s |")

    # ---------------- Task 1b
    L.append("\n## 1b. Chip at the CENTRE of an organoid, flat, scanning head: read time (s), 635 measured | 780 extrapolated  [m at 635]\n")
    L.append("| D (mm) | SPOT | mu_s' | from above | from below | plate camera NA 0.02, above, 635 |")
    L.append("|---|---|---|---|---|---|")
    for D in C.SPHERE_DIAMETERS_MM:
        for a in C.SPOT_SIZES_UM:
            for mu in C.MUSP_780_PER_MM:
                cells = []
                for side in ("above", "below"):
                    r6 = one(sres, D_mm=D, spot_um=a, musp_780=mu, cam=SCAN, side=side, wavelength_nm=635, tilt=0.0, **BASE)
                    r7 = one(sres, D_mm=D, spot_um=a, musp_780=mu, cam=SCAN, side=side, wavelength_nm=780, tilt=0.0, **BASE)
                    t6, t7 = rule.t_read(r6), rule.t_read(r7)
                    cells.append(f"{'yes' if t6 <= 60 else 'NO'} {fmt(t6)} \\| {'yes' if t7 <= 60 else 'NO'} {fmt(t7)} [{fmt(r6['m'])}]")
                rp = one(sres, D_mm=D, spot_um=a, musp_780=mu, cam=PLATE, side="above", wavelength_nm=635, tilt=0.0, **BASE)
                tp = rule.t_read(rp)
                cells.append(f"{'yes' if tp <= 60 else 'NO'} {fmt(tp)}")
                L.append(f"| {D} | {a} | {mu} | " + " | ".join(cells) + " |")

    # ---------------- Task 1c
    L.append("\n## 1c. Maximum depth (um) decoded within 60 s, flat chip (slab): 635 measured | 780 extrapolated\n")
    L.append("| SPOT | mu_s' | scanning head NA 0.25 | plate camera NA 0.02 |")
    L.append("|---|---|---|---|")
    for a in C.SPOT_SIZES_UM:
        for mu in C.MUSP_780_PER_MM:
            c = []
            for cn in (SCAN, PLATE):
                c.append(" \\| ".join(max_depth(rule, res, spot_um=a, musp_780=mu, wavelength_nm=lam, cam=cn, **BASE)
                                      for lam in (635, 780)))
            L.append(f"| {a} | {mu} | {c[0]} | {c[1]} |")

    # ---------------- Task 1d: dR sensitivity at 780 / 850
    L.append("\n## 1d. If the true reflectance change at 780/850 nm is smaller (baseline tissue, 100 um SPOT unless stated)\n")
    L.append("| wavelength, dR | dish chip, scan: t [m] | dish chip, plate NA 0.02: t | centre of 1 mm organoid, scan, above: t | "
             "centre configs readable (scan, above, of 27) | max depth, scan, 100 um SPOT | max depth, scan, 30 um SPOT |")
    L.append("|---|---|---|---|---|---|---|")
    sens = []
    for lam in C.WAVELENGTHS_V3:
        for rc, lab in (("paper635", "x1"), ("paper635_x0.5", "x0.5"), ("paper635_x0.25", "x0.25")):
            if lam == 635 and rc != "paper635":
                continue
            kw = dict(refl=rc, irradiance=10.0, mua=C.MUA_BASELINE)
            dish = one(res, placement="B_under", depth_um=0, spot_um=100, cam=SCAN, wavelength_nm=lam, musp_780=1.0, **kw)
            dishp = one(res, placement="B_under", depth_um=0, spot_um=100, cam=PLATE, wavelength_nm=lam, musp_780=1.0, **kw)
            cen = one(sres, D_mm=1.0, spot_um=100, musp_780=1.0, cam=SCAN, side="above", wavelength_nm=lam, tilt=0.0, **kw)
            nread = sum(rule.t_read(r) <= 60 for r in pick(sres, cam=SCAN, side="above", wavelength_nm=lam, tilt=0.0, **kw))
            md100 = max_depth(rule, res, spot_um=100, musp_780=1.0, wavelength_nm=lam, cam=SCAN, **kw)
            md30 = max_depth(rule, res, spot_um=30, musp_780=1.0, wavelength_nm=lam, cam=SCAN, **kw)
            label = f"{lam} nm, {lab}" + (" (measured)" if lam == 635 else "")
            L.append(f"| {label} | {fmt(rule.t_read(dish))} [{fmt(dish['m'])}] | {fmt(rule.t_read(dishp))} | "
                     f"{fmt(rule.t_read(cen))} | {nread} | {md100} | {md30} |")
            sens.append(dict(wavelength_nm=lam, dR_scale=lab, dish_scan_t=rule.t_read(dish), dish_m=dish["m"],
                             dish_plate_t=rule.t_read(dishp), centre1mm_t=rule.t_read(cen), centre_readable=nread,
                             maxdepth_100=md100, maxdepth_30=md30))
    M2.write_csv(os.path.join(out, "dR_sensitivity.csv"), sens)

    # ---------------- Task 2: random orientation at the centre
    L.append("\n## 2. Chip at the centre, RANDOM orientation, scanning head, from above (mirror SPOT)\n")
    L.append("| D (mm) | SPOT | mu_s' | 635: median t | 635: 90th pct | 635: within 1 s / 10 s / 60 s | 780: within 1 s / 60 s | flat chip, 635 |")
    L.append("|---|---|---|---|---|---|---|---|")
    orows = []
    for D in C.SPHERE_DIAMETERS_MM:
        for a in C.SPOT_SIZES_UM:
            for mu in C.MUSP_780_PER_MM:
                st = {}
                for lam in C.CENTRE_TILT_WAVELENGTHS:
                    tr = pick(sres, D_mm=D, spot_um=a, musp_780=mu, cam=SCAN, side="above", wavelength_nm=lam, **BASE)
                    st[lam] = orientation_stats(rule, tr)
                    orows.append(dict(D_mm=D, spot_um=a, musp_780=mu, wavelength_nm=lam, **st[lam]))
                flat = one(sres, D_mm=D, spot_um=a, musp_780=mu, cam=SCAN, side="above", wavelength_nm=635, tilt=0.0, **BASE)
                s6, s7 = st[635], st[780]
                L.append(f"| {D} | {a} | {mu} | {fmt(s6['median'])} | {fmt(s6['p90'])} | "
                         f"{s6['f1']:.0%} / {s6['f10']:.0%} / {s6['f60']:.0%} | {s7['f1']:.0%} / {s7['f60']:.0%} | "
                         f"{fmt(rule.t_read(flat))} |")
    M2.write_csv(os.path.join(out, "orientation.csv"), orows)
    key = [o for o in orows if o["D_mm"] == 1.0 and o["spot_um"] == 100 and o["musp_780"] == 1.0 and o["wavelength_nm"] == 635][0]

    # ---------------- Task 3: flatness
    tilt_v2 = load_csv(os.path.join(V2, "tilt.csv"))
    L.append("\n## 3a. How flat must a chip on the dish be? (SPOT facing the glass, no tissue in the path)\n")
    L.append("Tilt limit = largest tilt that still decodes within 60 s (round-2 tilt runs); optics-only limit = "
             "0.5*asin(2 NA / n) where the reflected cone leaves the lens entirely. Largest particle height "
             "h = side x tan(limit).\n")
    L.append("| reader | NA | tilt limit | optics-only limit | h max, 150 um chip | 200 um chip | 300 um chip | tilt from a 5 um particle (150/300 um chip) |")
    L.append("|---|---|---|---|---|---|---|---|")
    frows, tlim = [], {}
    for cn, NA in C.FLAT_NA.items():
        tr = pick(tilt_v2, placement="B_under", depth_um=0, cam=cn, mode="specular", spot_um=100)
        _, tmax = M2.readable_fraction(tr, rule, rule.req_for(tr[0]))
        tlim[cn] = tmax
        opt = M2.tilt_limit_deg(NA)
        hs = [h_max_um(s, tmax) for s in C.CHIP_SIDES_UM]
        t150 = math.degrees(math.atan(C.DEBRIS_UM / 150)); t300 = math.degrees(math.atan(C.DEBRIS_UM / 300))
        ok = "OK" if t150 <= tmax else ("OK for 300 um chips only" if t300 <= tmax else "fails")
        L.append(f"| {cn} | {NA} | {tmax:.2f} deg | {opt:.2f} deg | " + " | ".join(f"{h:.1f} um" for h in hs) +
                 f" | {t150:.1f} / {t300:.1f} deg: {ok} |")
        frows.append(dict(reader=cn, NA=NA, tilt_limit_deg=tmax, optics_limit_deg=opt,
                          **{f"hmax_{s}um": h for s, h in zip(C.CHIP_SIDES_UM, hs)}, debris_5um=ok))
    M2.write_csv(os.path.join(out, "flatness.csv"), frows)

    sres2 = load_csv(os.path.join(V2, "sphere.csv"))
    L.append(f"\n## 3b. Fraction of settled chips that can be read (tilt uniform 0-{C.SETTLE_TILT_DEG:g} deg, "
             "half land SPOT-up, 100 um SPOT, baseline tissue)\n")
    L.append("| reader | one SPOT, read from below | (a) SPOT on both faces, read from below | "
             "(b) one SPOT, read below + above, chip beside the organoid | (b) same, chip under a 1 mm organoid |")
    L.append("|---|---|---|---|---|")
    for cn in C.FLAT_NA:
        p_flat = min(1.0, tlim[cn] / C.SETTLE_TILT_DEG)
        # SPOT-up chip read from above: beside the organoid -> medium only (same tilt physics, 2 % glare);
        # under a 1 mm organoid -> through the whole organoid (round-2 'far_surface' sphere result).
        try:
            far = one(sres2, placement="far_surface", side="above", D_mm=1.0, spot_um=100, musp_780=1.0, cam=cn)
            p_under = 1.0 if rule.t_read(far) <= 60 else 0.0
            under = f"{0.5 * p_flat + 0.5 * p_under:.0%}"
        except KeyError:
            under = "not simulated"
        L.append(f"| {cn} | {0.5 * p_flat:.0%} | {p_flat:.0%} | {p_flat:.0%} | {under} |")

    # ---------------- Task 4: sensitivity ranking
    rk = []
    D2 = dict(musp_780=1.0, **BASE)
    dish = lambda **kw: one(res, placement="B_under", depth_um=0, spot_um=100, cam=SCAN, wavelength_nm=635, **{**D2, **kw})
    cen1 = lambda **kw: one(sres, D_mm=1.0, spot_um=100, cam=SCAN, side="above", wavelength_nm=635, **{**D2, "tilt": 0.0, **kw})
    cen2 = lambda **kw: one(sres, D_mm=2.0, spot_um=100, cam=SCAN, side="above", wavelength_nm=635, **{**D2, "tilt": 0.0, **kw})
    md = lambda **kw: max_depth(rule, res, spot_um=100, cam=SCAN, wavelength_nm=635, **{**D2, **kw})

    def rng_txt(vals):
        v = [x for x in vals if x is not None]
        if not v:
            return "not run"
        lo, hi = min(v), max(v)
        return f"{fmt(lo)}-{fmt(hi)} s"

    def score(*lists):
        sc = 0.0
        for v in lists:
            v = [x for x in v if x is not None]
            if v:
                lo, hi = min(v), max(v)
                sc = max(sc, 99.0 if not math.isfinite(hi) else math.log10(hi / lo))
        return sc

    def entry(name, rng, d, c1, c2, mdl, bench):
        rk.append(dict(input=name, range=rng, dish_t=rng_txt(d), centre1_t=rng_txt(c1), centre2_t=rng_txt(c2),
                       max_depth=" / ".join(mdl), score=score(d, c1, c2), bench=bench))
    T = rule.t_read
    refl = ["paper635", "paper635_x0.5", "paper635_x0.25"]
    entry("reflectance change dR", "100% to 25% of the 635 nm value", [T(dish(refl=r)) for r in refl],
          [T(cen1(refl=r)) for r in refl], [T(cen2(refl=r)) for r in refl], [md(refl=r) for r in refl],
          "bare-chip reflectance at 635 and 780 nm under the reader's own light")
    mus = C.MUSP_780_PER_MM
    entry("tissue scattering mu_s'", "0.3-2.0 /mm (at 780)", [T(dish(musp_780=m)) for m in mus],
          [T(cen1(musp_780=m)) for m in mus], [T(cen2(musp_780=m)) for m in mus], [md(musp_780=m) for m in mus],
          "organoid mu_s' (OCT attenuation, or integrating sphere on sections)")
    mua = C.MUA_PER_MM
    entry("absorption mu_a", "0.01-0.05 /mm", [T(dish(mua=x)) for x in mua], [T(cen1(mua=x)) for x in mua], [None],
          [md(mua=x) for x in mua], "organoid absorption spectrum (spectrophotometry of a homogenate)")
    Es = C.IRRADIANCE_MW_CM2
    entry("light level", "1-100 mW/cm2 (reading only; the chip's power needs ~10)", [T(dish(irradiance=e)) for e in Es],
          [T(cen1(irradiance=e)) for e in Es], [T(cen2(irradiance=e)) for e in Es], [md(irradiance=e) for e in Es],
          "power meter at the sample plane; check the camera saturates")
    nz = C.BLINK_NOISE
    entry("added noise at the blink frequency", "0 to 1e-2 per sqrt(Hz) (apparent m in a 1 s average)",
          [t_read(rule, dish(), snr_with_blink_noise(dish(), x)) for x in nz],
          [t_read(rule, cen1(), snr_with_blink_noise(cen1(), x)) for x in nz],
          [t_read(rule, cen2(), snr_with_blink_noise(cen2(), x)) for x in nz],
          [max_depth(rule, res, ok=lambda r, x=x: t_read(rule, r, snr_with_blink_noise(r, x)) <= 60,
                     spot_um=100, cam=SCAN, wavelength_nm=635, **D2) for x in nz],
          "lock-in recording of an unpowered chip inside a real organoid (apparent m vs averaging time)")
    trd = [r for r in tilt_v2 if r["placement"] == "B_under" and r["depth_um"] == 0 and r["cam"] == SCAN
           and r["mode"] == "specular" and r["spot_um"] == 100 and r["tilt"] in (0.0, 2.0, 5.0, 10.0)]
    k2 = [o for o in orows if o["D_mm"] == 2.0 and o["spot_um"] == 100 and o["musp_780"] == 1.0 and o["wavelength_nm"] == 635][0]
    entry("chip orientation", "dish: tilt 0-10 deg; centre: flat vs random (90th percentile)",
          [T(r) for r in trd], [T(cen1()), key["p90"]], [T(cen2()), k2["p90"]], ["n/a"],
          "image settled / embedded chips to get their tilt distribution; wedge test under the reader")
    rk.sort(key=lambda r: -r["score"])
    L.append("\n## 4. Sensitivity ranking (635 nm, scanning head, 100 um SPOT, baseline tissue unless varied), "
             "ranked by the largest change in read time\n")
    L.append("| rank | input | range tested | chip on dish | centre, 1 mm organoid | centre, 2 mm organoid | "
             "max depth (um) across the range | bench measurement that pins it |")
    L.append("|---|---|---|---|---|---|---|---|")
    for i, r in enumerate(rk, 1):
        L.append(f"| {i} | {r['input']} | {r['range']} | {r['dish_t']} | {r['centre1_t']} | {r['centre2_t']} | "
                 f"{r['max_depth']} | {r['bench']} |")
    M2.write_csv(os.path.join(out, "sensitivity.csv"), rk)

    open(os.path.join(out, "tables_v3.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))
    return rule


